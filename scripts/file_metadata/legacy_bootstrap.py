class BootstrapError(RuntimeError): pass

def verify_bridge_trees(legacy_tree, anchor_tree):
    added = sorted(set(anchor_tree) - set(legacy_tree))
    removed = sorted(set(legacy_tree) - set(anchor_tree))
    changed = sorted(path for path in set(legacy_tree) & set(anchor_tree)
                     if (legacy_tree[path].mode, legacy_tree[path].oid) != (anchor_tree[path].mode, anchor_tree[path].oid))
    if added != sorted(ALLOWED_BRIDGE_ADDITIONS) or removed or changed:
        raise BootstrapError(f'legacy bridge mismatch: added={added}, removed={removed}, common_mode_or_oid_changes={changed[:20]}')
    return added, removed, changed

def match_purpose(path, subject_entry, proposal_source_tree, proposals):
    proposal = proposals.get(path)
    source_entry = proposal_source_tree.get(path)
    if (proposal is None or source_entry is None or proposal.get('path') != path or
            proposal.get('mode') != source_entry.mode or proposal.get('oid') != source_entry.oid or
            (source_entry.mode, source_entry.oid) != (subject_entry.mode, subject_entry.oid)):
        raise BootstrapError(f'{path}: no exact path+mode+OID purpose proposal matched the fixed subject')
    return proposal

def _json_bytes(raw, label):
    try: return json.loads(raw.decode('utf-8', 'strict'), object_pairs_hook=mt._pairs)
    except (UnicodeError, json.JSONDecodeError, mt.ManifestError) as exc: raise BootstrapError(f'{label}: invalid strict JSON: {exc}') from exc

def _blob_at(repo, commit, path):
    ent = repo._tree_entry_for_path(commit, path.encode('utf-8'))
    if ent is None: raise BootstrapError(f'{commit}:{path} is absent')
    mode, typ, oid = ent
    repo._verify_path_blob(commit, path.encode('utf-8'), oid, mode)
    if typ != 'blob': raise BootstrapError(f'{commit}:{path} is not a blob')
    return repo.blob(oid), oid

def _git_date(repo, sha):
    ts = int(repo.run('show', '-s', '--format=%ct', sha).strip())
    return datetime.fromtimestamp(ts, timezone.utc).date().isoformat()

def _verify_created(repo, path, evidence, anchor_sha):
    value, source = evidence.get('value'), evidence.get('source', {})
    if value == 'unknown' and source.get('kind') == 'unknown': return False, 'old created was explicitly unknown'
    commit, source_path = source.get('commit'), source.get('path', path)
    if not isinstance(commit, str) or not re.fullmatch(r'[0-9a-f]{40,64}', commit): return False, 'old created has no full commit SHA'
    try:
        commit_sha, _ = repo.commit_identity(commit)
        repo.run('merge-base', '--is-ancestor', commit_sha, anchor_sha)
        if _git_date(repo, commit_sha) != value: return False, 'old created date differs from UTC committer date'
        raw = source_path.encode('utf-8', 'strict')
        ent = repo._tree_entry_for_path(commit_sha, raw)
        if ent is None: return False, 'old created source path absent from commit'
        mode, _, oid = ent
        repo._verify_path_blob(commit_sha, raw, oid, mode)
        if mt._identity_path_at_commit(repo, path, anchor_sha, commit_sha) != source_path:
            return False, 'old created source path is outside identity lineage'
        return True, ''
    except (GitInventoryError, mt.ManifestError, UnicodeError, ValueError) as exc:
        return False, str(exc)

def _same_earliest_created(old_evidence, expected):
    """Only accept a source that matches the Git-walk's earliest identity add."""
    source=old_evidence.get('source',{})
    expected_path=expected.source.get('path')
    return (old_evidence.get('value')==expected.value
        and source.get('commit')==expected.source.get('commit')
        and source.get('path')==expected_path
        and source.get('kind')==expected.source.get('kind'))

def _reason_prefix(reason, anchor):
    return f'Rederived from main anchor {anchor}: {reason}'

def _evidence_obj(ev, anchor, reason):
    source = dict(ev.source)
    source['reason'] = _reason_prefix(f'{reason}; {source.get("reason", "No traceable source.")}', anchor)
    return {'value': ev.value, 'source': source}

def _exception_for(path, rule):
    explanations = {
        'frozen-test-fixtures':'Frozen test fixture consumed by tests as exact serialized input; keep its bytes unchanged.',
        'strict-json':'Strict JSON is consumed as structured data and has no safe comment syntax; keep the exact data contract.',
        'lock-and-module-integrity':'Package/module integrity data is tool-owned; keep its exact parser and integrity bytes.',
        'sql-migrations':'Versioned SQL migration bytes are part of the applied database history and remain immutable.',
        'binary-assets':'Binary payload cannot carry a safe text header; preserve payload bytes and record metadata out of band.',
        'license-text':'Operative license text must remain exact and independent of file metadata.',
        'generated-wire-types':'Generated output must remain byte-aligned with its declared generator and input.',
        'third-party-derived-source':'Preserve upstream copyright and disclaimer text verbatim; project authorship remains separate.',
        'dockerfile-parser-directives':'Docker parser directives must remain at byte zero until safe insertion is verified.',
        'unknown-author-rights':'No author or rights source is available for this exact image; preserve unknown attribution and do not infer ownership.',
        'bootstrap-registry-js':'This exact JavaScript consumer configuration has no verified safe in-band metadata location; preserve its bytes.',
        'bootstrap-registry-markdown':'This exact Markdown file contains literal metadata-marker examples; preserve its original bytes without parsing those examples as a header.',
        'bootstrap-literal-marker-python':'This exact Python file defines or tests literal metadata markers; preserve its raw bytes.',
        'bootstrap-applied-migration':'This exact versioned SQL migration is present in the fixed subject and is treated as applied history; preserve its bytes and record its object hash.',
    }
    why = explanations.get(rule['id'], rule.get('reason') or 'No safe in-band metadata position is approved for this exact file.')
    return {'rule_id':rule['id'],'source':path,'reason':f'{path}: {why}'}

def _refresh_handling_fields(path, rec, rule):
    rec['handling'] = rule['handling']
    rec['header_state'] = {'header-and-manifest':'pending-header-application','manifest-only':'manifest-only',
                           'preserve-notice-and-manifest':'upstream-notice-preserved',
                           'generated-manifest-only':'generator-owned-output'}[rule['handling']]
    if rule.get('reason') or rule['handling'] != 'header-and-manifest': rec['exception'] = _exception_for(path, rule)

def _purpose_ok(purpose, schema):
    minimum = schema['$defs']['record']['properties']['purpose'].get('minLength', 1)
    if not isinstance(purpose, str) or len(purpose.strip()) < minimum: return False
    low = purpose.lower()
    return not any(x in low for x in ('main/run internal package behavior','implements operations','component-hook','data and objects'))

def _window_revision(previous, before, after, rule, path):
    if before.mode == after.mode and before.oid == after.oid: return previous, True
    same_body = mt._same_normalized_body(before, after, rule, path)
    match = REVISION_RE.fullmatch(previous)
    if not match: raise BootstrapError(f'{path}: invalid prior revision {previous!r}')
    changed = not same_body or before.mode != after.mode or before.object_type != after.object_type
    return (f'r{int(match.group(1))+1}' if changed else previous), same_body


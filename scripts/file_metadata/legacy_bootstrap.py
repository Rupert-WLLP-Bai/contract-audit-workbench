    candidate['file_classes'] = added_classes + classes
    subjects = sorted({'docs-site/bun.lock', *extra_paths, *migrations, *docker_paths})
    records=[]
    for path in subjects:
        if path not in subject_tree: raise BootstrapError(f'policy delta path is absent from fixed subject: {path}')
